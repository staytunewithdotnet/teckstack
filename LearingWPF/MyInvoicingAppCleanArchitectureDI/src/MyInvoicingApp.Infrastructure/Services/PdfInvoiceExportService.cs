using MyInvoicingApp.Application.DTOs;
using MyInvoicingApp.Application.Interfaces;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace MyInvoicingApp.Infrastructure.Services;

public class PdfInvoiceExportService : IPdfExportService
{
    static PdfInvoiceExportService()
    {
        // QuestPDF community license - free for this learning/production case study
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public async Task<string> ExportSingleInvoiceToPdfAsync(InvoiceDto invoice, string filePath)
    {
        return await Task.Run(() =>
        {
            var dir = Path.GetDirectoryName(filePath);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4);
                    page.Margin(2, Unit.Centimetre);
                    page.DefaultTextStyle(x => x.FontSize(11));
                    
                    page.Header().Column(col =>
                    {
                        col.Item().Text("INVOICE").FontSize(24).Bold().FontColor(Colors.Blue.Darken2);
                        col.Item().Text($"#{invoice.Id.ToString().Substring(0,8).ToUpper()}").FontSize(10).FontColor(Colors.Grey.Medium);
                        col.Item().PaddingVertical(10).LineHorizontal(1).LineColor(Colors.Grey.Lighten2);
                    });

                    page.Content().Column(col =>
                    {
                        col.Spacing(16);
                        col.Item().Row(row =>
                        {
                            row.RelativeItem().Column(c =>
                            {
                                c.Item().Text("Bill To:").Bold();
                                c.Item().Text(invoice.CustomerName).FontSize(14).Bold();
                                c.Item().Text(invoice.Description);
                            });
                            row.ConstantItem(150).Column(c =>
                            {
                                c.Item().Text("Date:").Bold();
                                c.Item().Text(invoice.CreatedAt.ToString("yyyy-MM-dd HH:mm"));
                                c.Item().Text("Status:").Bold().PaddingTop(8);
                                c.Item().Text(invoice.IsPaid ? "PAID" : "PENDING")
                                    .FontColor(invoice.IsPaid ? Colors.Green.Darken1 : Colors.Orange.Darken1).Bold();
                            });
                        });

                        col.Item().PaddingTop(10).Table(table =>
                        {
                            table.ColumnsDefinition(cols =>
                            {
                                cols.ConstantColumn(100);
                                cols.RelativeColumn();
                                cols.ConstantColumn(80);
                            });

                            table.Header(header =>
                            {
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(8).Text("Qty").Bold();
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(8).Text("Description").Bold();
                                header.Cell().Background(Colors.Grey.Lighten3).Padding(8).AlignRight().Text("Amount").Bold();
                            });

                            table.Cell().Padding(8).Text("1");
                            table.Cell().Padding(8).Text(invoice.Description ?? invoice.CustomerName);
                            table.Cell().Padding(8).AlignRight().Text($"{invoice.Amount:N2}");

                            table.Cell().ColumnSpan(2).Padding(8).AlignRight().Text("Subtotal").Bold();
                            table.Cell().Padding(8).AlignRight().Text($"{invoice.Amount:N2}");

                            table.Cell().ColumnSpan(2).Padding(8).AlignRight().Text($"Tax ({18}%)").Bold();
                            table.Cell().Padding(8).AlignRight().Text($"{invoice.Tax:N2}");

                            table.Cell().ColumnSpan(2).Background(Colors.Blue.Lighten5).Padding(8).AlignRight().Text("Total").Bold().FontSize(12);
                            table.Cell().Background(Colors.Blue.Lighten5).Padding(8).AlignRight().Text($"{invoice.Total:N2}").Bold().FontSize(12);
                        });

                        col.Item().PaddingTop(20).Text($"Thank you for your business! This invoice was generated by MyInvoicingApp (Clean Architecture WPF)").FontSize(9).FontColor(Colors.Grey.Medium).Italic();
                        col.Item().Text($"DB Source: File-based SQLite - Production Ready").FontSize(8).FontColor(Colors.Grey.Lighten1);
                    });

                    page.Footer().AlignCenter().Text(x =>
                    {
                        x.Span("Page ").FontSize(9);
                        x.CurrentPageNumber().FontSize(9);
                        x.Span(" of ").FontSize(9);
                        x.TotalPages().FontSize(9);
                    });
                });
            }).GeneratePdf(filePath);

            return filePath;
        });
    }

    public async Task<string> ExportInvoicesListToPdfAsync(List<InvoiceDto> invoices, string filePath)
    {
        return await Task.Run(() =>
        {
            var dir = Path.GetDirectoryName(filePath);
            if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);

            Document.Create(container =>
            {
                container.Page(page =>
                {
                    page.Size(PageSizes.A4.Landscape());
                    page.Margin(1.5f, Unit.Centimetre);
                    page.Header().Text($"Invoices Report - {invoices.Count} invoices - {DateTime.Now:yyyy-MM-dd}").Bold().FontSize(16);
                    page.Content().Table(table =>
                    {
                        table.ColumnsDefinition(c =>
                        {
                            c.RelativeColumn(2);
                            c.RelativeColumn(3);
                            c.ConstantColumn(80);
                            c.ConstantColumn(80);
                            c.ConstantColumn(80);
                            c.ConstantColumn(110);
                            c.ConstantColumn(50);
                        });

                        table.Header(h =>
                        {
                            foreach(var title in new[]{"Customer","Description","Amount","Tax","Total","Created","Paid"})
                                h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text(title).Bold().FontSize(9);
                        });

                        foreach(var inv in invoices)
                        {
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).Text(inv.CustomerName).FontSize(9);
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).Text(inv.Description).FontSize(9);
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).AlignRight().Text($"{inv.Amount:N2}").FontSize(9);
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).AlignRight().Text($"{inv.Tax:N2}").FontSize(9);
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).AlignRight().Text($"{inv.Total:N2}").FontSize(9).Bold();
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).Text(inv.CreatedAt.ToString("yyyy-MM-dd")).FontSize(8);
                            table.Cell().BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(5).Text(inv.IsPaid ? "Yes" : "No").FontSize(9);
                        }
                    });
                });
            }).GeneratePdf(filePath);

            return filePath;
        });
    }

    public Task<string> ExportSingleInvoiceToPdfAsync(InvoiceDto invoice)
    {
        var path = Path.Combine(Path.GetTempPath(), $"Invoice_{invoice.CustomerName}_{DateTime.Now:yyyyMMdd_HHmmss}.pdf");
        return ExportSingleInvoiceToPdfAsync(invoice, path);
    }
}
